import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const must=(v,m)=>{if(!v)throw new Error(m)};
const pkg=JSON.parse(read('package.json'));
const core=read('src/core/runtime.js');
const cert=read('src/features/certificates/runtime.js');
const css=read('src/styles/certificates.css');
const vector=read('src/features/reports/vector-pdf-runtime.js');
must(['2.41.1','2.41.2'].includes(pkg.version),'package version must preserve v2.41.1+ behavior');
must(/APP_VERSION_NAME='2\.41\.[12]'/.test(core)&&/APP_VERSION_CODE=2410[12]/.test(core),'runtime version/code mismatch');
must(cert.includes('fitCertificatePreview')&&cert.includes('baseW=1122')&&cert.includes('baseH=794'),'responsive fixed-canvas preview missing');
must(cert.includes('certPreviewZoom')&&cert.includes('previewZoom:92'),'preview zoom control missing');
must(css.includes('width:1122px;height:794px')&&css.includes('.cert-preview-stage'),'fixed A4 preview canvas missing');
must(!css.includes('min-width:700px')&&!css.includes('min-width:720px'),'old overflowing mobile preview constraints remain');
must(!css.includes('max-width:12vw')&&!css.includes('max-height:12vw'),'logo size is still capped by viewport');
must(cert.includes('max="230"')&&css.includes('width:var(--cert-logo-size)'),'working logo size control missing');
must(cert.includes('islamicPatternSvg')&&cert.includes('islamicCornerSvg')&&css.includes('.cert-corner-line.primary')&&css.includes('.cert-geo-bg'),'real SVG Islamic geometry missing');
must(!css.includes('conic-gradient')&&!css.includes('clip-path:polygon(0 0,100% 0,100% 35%'),'old triangle/conic ornament remains');
must(cert.includes('cert-number-logo')||cert.includes('cert-number-meta'),'safe certificate number placement missing');
must(css.includes('.cert-verse'),'certificate verse separation missing');
must(cert.includes('position:static!important')&&cert.includes('transform:none!important'),'certificate vector HTML must reset preview scaling/position');
must(vector.includes("clone.style.position='static'")&&vector.includes("clone.style.left='auto'")&&vector.includes("clone.style.top='auto'"),'vector clone must clear preview positioning');
console.log('v2.41.1 certificate preview/geometry checks passed ✅');
