import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const must=(v,m)=>{if(!v)throw new Error(m)};
const pkg=JSON.parse(read('package.json'));
const core=read('src/core/runtime.js');
const legacy=read('src/legacy/app.js');
const reports=read('src/features/reports/runtime.js');
const main=read('src/main.js');
must(pkg.version==='2.18.2','package version must be 2.18.2');
must(core.includes("APP_VERSION_NAME='2.18.2'")&&core.includes('APP_VERSION_CODE=21802'),'runtime version mismatch');
must(main.includes("version: '2.18.2'"),'ready event must expose 2.18.0');
must(core.includes('check(3000)')&&core.includes('check(1800)'),'network health retry/timeouts missing');
must(legacy.includes('async function refreshAdminUsers'),'direct admin users refresh missing');
must(legacy.includes('users:roleCanAdmin()?(state.users||[]):[]'),'admin users are not cached safely');
must(legacy.includes('state.users=roleCanAdmin()?(x.users||[]):[]'),'admin users cache restore missing');
must(legacy.includes('adminUsersReadOnly()'),'offline admin mutation guard missing');
must(reports.includes("REPORT_CACHE_PREFIX='halaqati_v2177_report_cache_'"),'complete report cache missing');
must(reports.includes('loadServerReportData(b)'),'server-first report loader missing');
must(!reports.includes('if(!(await internetReachable()))'),'report loader still gates server fetch behind health check');
must(reports.includes('تعذر تحميل التقرير من الخادم ولا توجد نسخة محلية كاملة'),'unsafe zero-report fallback was not removed');
must(reports.includes("state.reportSource='server'")&&reports.includes("state.reportSource='cache'"),'report source tracking missing');
console.log('Halaqati v2.18.0 server-first admin/reports checks passed.');
